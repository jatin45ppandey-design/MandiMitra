export type TranslationKey = keyof typeof hi
export const translations: Record<Language, TranslationShape> = { hi, en }

export function translate(
  language: Language,
  key: TranslationKey,
  replacements?: Record<string, string | number>,
): string {
  let value = translations[language][key]
  Object.entries(replacements ?? {}).forEach(([token, replacement]) => {
    value = value.replace(`{${token}}`, String(replacement))
  })
  return value
}

